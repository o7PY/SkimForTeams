"""Storage interface. Implementations: memory.py (tests/local), postgres.py."""
from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol

from ..normalize import MessageEvent


class Storage(Protocol):
    async def start(self) -> None: ...
    async def close(self) -> None: ...
    async def ping(self) -> bool: ...

    async def insert_raw(self, row: dict) -> tuple[int, bool]:
        """Store a raw activity. Returns (id, inserted); inserted=False for a duplicate dedupe_key."""

    async def upsert_team(self, team: dict) -> None: ...
    async def mark_team_installed(self, team_id: str, pairing_code: str, by_aad: str | None, at: datetime) -> None: ...
    async def claim_welcome(self, team_id: str, at: datetime) -> bool:
        """Atomically mark the welcome as sent for this install. True only for the first caller."""

    async def mark_team_removed(self, team_id: str, at: datetime) -> None: ...
    async def upsert_conversation(self, conv: dict) -> None: ...

    async def apply_message_event(self, ev: MessageEvent, raw_id: int) -> bool:
        """Create/edit/delete/undelete a message with versioning (D-011).
        Returns False if an edit/delete/undelete arrived for a message we had never seen
        (the row is still created from it)."""

    async def add_attachments(self, rows: list[dict], raw_id: int) -> None: ...
    async def add_reactions(self, rows: list[dict], raw_id: int) -> None: ...

    # --- debug/read side (FR-11) ---
    async def list_raw(self, limit: int, type: str | None) -> list[dict]: ...
    async def list_messages(self, limit: int, team_id: str | None, conversation_id: str | None) -> list[dict]: ...
    async def get_message(self, conversation_id: str, message_id: str) -> dict[str, Any] | None: ...
    async def list_teams(self) -> list[dict]: ...
